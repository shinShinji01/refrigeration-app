// Кусок изоляции — обычно единицы-десятки см², группа/набор в статистике —
// доли-единицы м² (docs/spec.md → "квадратных метрах"). Один кусок в м² читался
// бы как "0.03 м²" — не наглядно, поэтому единица подбирается по величине.
export const formatArea = (areaMm2: number): string => {
  if (areaMm2 >= 1_000_000) {
    return `${(areaMm2 / 1_000_000).toFixed(2)} м²`
  }
  return `${(areaMm2 / 100).toFixed(1)} см²`
}
